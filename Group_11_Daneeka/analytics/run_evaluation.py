"""Monte-Carlo evaluation: N randomised missions per condition (baseline vs proposed).

Every mission runs the full MuJoCo physics (500 Hz) + sensor + environment + FSM stack.
The same seed gives both conditions the SAME farm (defects, confounders, weather, start time,
wheel-calibration / gyro-bias draws), so differences come from the controller, not from luck.

Outputs
  analytics/solar_inspection_real_trials.csv   one row per mission (this file is generated by
                                               src/solar_defect_detector.py, never typed by hand)
  results/telemetry/<cond>_seed<k>.csv         500 Hz telemetry for the first few seeds
Usage:  python analytics/run_evaluation.py --n 30 --workers 2
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import multiprocessing as mp
import os
import sys
import time

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from fault_injection import FaultConfig, NavFaults, SensorFaults  # noqa: E402
from solar_defect_detector import InspectionMission, MissionConfig  # noqa: E402
from solar_environment import EnvConfig  # noqa: E402

MODEL = os.path.join(ROOT, "models", "solar_defect_amr.xml")
SEED0 = 3000   # held-out evaluation seeds; thresholds were tuned on seeds 1000-1029 (analytics/tuning_trials_seeds1000.csv)
WEATHERS = ["clear", "clear", "hazy", "windy_clear", "partly_cloudy"]


def make_config(seed: int, condition: str, scenario: str = "random_nominal") -> MissionConfig:
    r = np.random.default_rng(seed + 777)
    weather = WEATHERS[int(r.integers(0, len(WEATHERS)))]
    start_h = float(r.uniform(10.0, 14.0))
    env = EnvConfig(date=dt.date(2026, 10, 31), start_s=start_h * 3600.0, weather=weather,
                    moving_cloud=(weather == "partly_cloudy"))
    faults = FaultConfig(NavFaults(), SensorFaults(), label=scenario)
    cfg = MissionConfig(condition=condition, seed=seed, env=env, faults=faults,
                        log_telemetry=True)
    cfg.weather_label = weather
    cfg.start_h = start_h
    return cfg


FIELDS = ["seed", "condition", "weather", "start_h", "completed", "duration_s", "wall_s", "n_defects",
          "n_confounders", "tp", "fp", "fn", "tn", "precision", "recall", "conf_fp", "kind_accuracy",
          "loc_err_mean_m", "loc_err_max_m", "modules_scanned", "farm_mw", "time_per_mw_h",
          "control_effort", "track_rmse_m", "track_max_m", "heading_rmse_rad", "pose_err_rms_m",
          "pose_err_max_m", "unassessed", "deferred", "obstacle_contact_s"]


def run_one(args):
    seed, cond, save_tel = args
    cfg = make_config(seed, cond)
    res = InspectionMission(cfg, MODEL).run()
    row = dict(res.metrics)
    row.update(weather=cfg.weather_label, start_h=round(cfg.start_h, 3))
    if save_tel and res.telemetry is not None:
        res.telemetry.to_csv(os.path.join(ROOT, "results", "telemetry", f"{cond}_seed{seed}.csv"))
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=30)
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--save-telemetry", type=int, default=2, help="number of seeds whose 500 Hz CSV is written")
    ap.add_argument("--out", default=os.path.join(ROOT, "analytics", "solar_inspection_real_trials.csv"))
    a = ap.parse_args()
    os.makedirs(os.path.join(ROOT, "results", "telemetry"), exist_ok=True)
    jobs = [(SEED0 + k, c, k < a.save_telemetry) for k in range(a.n) for c in ("baseline", "proposed")]
    t0 = time.time()
    rows = []
    with mp.Pool(a.workers) as pool:
        for i, row in enumerate(pool.imap(run_one, jobs), 1):
            rows.append(row)
            print(f"[{i}/{len(jobs)}] seed {row['seed']} {row['condition']:9s} recall={row['recall']:.2f} "
                  f"prec={row['precision']:.2f} t={row['duration_s']:.0f}s  elapsed {time.time() - t0:.0f}s", flush=True)
    with open(a.out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    print("wrote", a.out)


if __name__ == "__main__":
    main()
