"""Write ``docs/CAPSTONE_RESULTS.md`` and ``docs/STANDARDS_COMPLIANCE.md`` from the files in ``analytics/``.

    python scripts/make_capstone_doc.py

Every number in both documents is read from ``analytics/`` at run time; run the Monte Carlo
(``experiments/09_capstone_monte_carlo.py``), ``analytics/aed_delivery_roi.py`` and
``analytics/standards_check.py`` first.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
A, DOCS = ROOT / "analytics", ROOT / "docs"


def table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    head = "| " + " | ".join(cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)) + "\n"


def g(x, nd: int = 4) -> str:
    if isinstance(x, str):
        return x
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    if isinstance(x, float) and math.isinf(x):
        return "inf"
    return f"{x:.{nd}g}"


def results_doc() -> str:
    trials = pd.read_csv(A / "aed_delivery_real_trials.csv")
    stats = pd.read_csv(A / "capstone_statistics.csv")
    succ = pd.read_csv(A / "capstone_success_rates.csv")
    roi = json.loads((A / "roi_results.json").read_text(encoding="utf-8"))
    fmea = pd.read_csv(A / "fmea.csv")
    res, be = roi["results"], roi["break_even"]
    meta = json.loads((A / "capstone_run_meta.json").read_text(encoding="utf-8")) if (A / "capstone_run_meta.json").exists() else {}

    out = ["# Capstone results (generated)\n",
           "Generated by `scripts/make_capstone_doc.py` from `analytics/`. Do not edit by hand; re-run the scripts instead.\n",
           "## Monte Carlo (MuJoCo, 500 Hz)\n",
           f"{len(trials)} episodes: {meta.get('n_per_condition', '?')} per condition and controller, conditions "
           f"{', '.join(sorted(trials['condition'].unique()))}. Seeds {int(trials['seed'].min())} to {int(trials['seed'].max())}, "
           f"one per row. Achieved log rate {trials['log_rate_hz'].min():.1f} to {trials['log_rate_hz'].max():.1f} Hz.\n",
           "### Success rate (goal reached), Wilson 95 % interval\n"]
    s = succ.copy()
    for c in ("rate", "ci95_low", "ci95_high"):
        s[c] = s[c].map(lambda v: f"{100 * v:.1f} %")
    out.append(table(s[["condition", "controller", "successes", "n", "rate", "ci95_low", "ci95_high"]]))
    keep = ["condition", "metric", "unit", "n_a", "n_b", "mean_baseline", "sd_baseline", "mean_proposed", "sd_proposed",
            "t", "df", "p", "cohens_d", "diff_ci95_low", "diff_ci95_high"]
    for comp in sorted(stats["comparison"].unique()):
        out.append(f"### {comp.capitalize()} (Welch t-test on successful runs; difference = baseline - second arm)\n")
        st = stats[(stats["comparison"] == comp) & stats["condition"].isin(["PROTOCOL", "ALL"])].copy()
        st = st[[c for c in keep if c in st.columns]]
        for c in st.columns[5:]:
            st[c] = st[c].map(g)
        out.append(table(st))
    out.append("`PROTOCOL` pools free_flow, lane_splitting and crowd (the titles-sheet protocol); `ALL` adds the kerb and "
               "slippery stress conditions. Failed runs have no transit time and are excluded from these tests; the "
               "success-rate table above carries them.\n")
    out.append("## Business model (dimensionless; costs in ALS vehicle-years)\n")
    keys = ["hubs", "pods", "calls_per_day", "H_reclaimed_veh_h_per_day", "delta_FTE", "C_baseline", "C_robot", "kappa", "NCRI",
            "T_payback_months", "P_payback", "lambda_per_hub_h", "mu_per_h", "rho", "p_wait", "Wq_min",
            "t_first_shock_pod_min", "t_first_shock_ambulance_min", "delta_survival", "delta_QALY_per_encounter",
            "QALY_per_year", "QALY_per_ALS_vehicle_year_of_cost"]
    out.append(table(pd.DataFrame({"quantity": keys, "value": [g(res[k]) for k in keys]})))
    out.append(f"Break-even on `{roi['sensitivity_input']}`: " + "; ".join(f"{k}: {g(v)}" for k, v in be.items()) + ".\n")
    scen = pd.read_csv(A / "roi_scenarios.csv")
    for c in ("H_reclaimed_veh_h_per_day", "kappa", "NCRI"):
        scen[c] = scen[c].map(g)
    out.append("### What would have to be true: labelled scenarios (their inputs are assumptions)\n")
    out.append(table(scen[["scenario", "pods", "H_reclaimed_veh_h_per_day", "kappa", "NCRI", "meets_kappa_target"]]))
    need = roi.get("standdown_calls_per_pod_day_needed_for_kappa_0.25", {})
    if need:
        out.append("Stand-down calls per pod per day needed for kappa <= 0.25: " + "; ".join(f"{k.replace(chr(95), chr(32))} {g(v)}" for k, v in need.items()) + ".\n")
    out.append("Inputs (each is sourced or labelled ASSUMPTION):\n")
    out.append(table(pd.read_csv(A / "roi_inputs.csv")))
    out.append("## FMEA (occurrence from the measured failure rates)\n")
    f = fmea[["failure_mode", "S", "O_pre", "D_pre", "RPN_pre", "rate_pre", "pre_arm", "O_post", "D_post", "RPN_post",
              "rate_post", "post_arm", "RPN_reduction_pct", "shown_in"]].copy()
    for c in ("rate_pre", "rate_post"):
        f[c] = f[c].map(lambda v: f"{100 * v:.1f} %")
    f["RPN_reduction_pct"] = f["RPN_reduction_pct"].map(lambda v: f"{v:.0f} %")
    out.append(table(f))
    return "\n".join(out)


def standards_doc() -> str:
    std = pd.read_csv(A / "standards_check.csv")
    lines = ["# Standards compliance (generated)\n",
             "Generated by `scripts/make_capstone_doc.py` from `analytics/standards_check.csv`. Clause text follows the course's "
             "`ACADEMIC_AND_INDUSTRY_STANDARDS_MANUAL.md`; the standards themselves are paywalled and were not read for this project.\n",
             "## Applicability\n",
             table(pd.DataFrame([
                 ["ISO 10218-1/-2", "No", "industrial robot-arm cells; the pod is a mobile vehicle with no manipulator"],
                 ["ISO 3691-4", "Partly", "braking, detection field and detection zones transfer; it is written for industrial trucks, the pod runs on sidewalks"],
                 ["ANSI/RIA R15.06", "No", "US adoption of ISO 10218"],
                 ["IEC 60601-1", "Partly", "the AED is the medical device; the pod only limits payload shock (3 g budget)"],
                 ["Domain-specific", "Yes", "no sidewalk-robot standard covers India; the design assumes the limits below"],
             ], columns=["standard", "applies", "why"])),
             "## Requirement checks\n", table(std[["standard", "requirement", "required", "achieved", "status"]]),
             "`DEVIATION` rows are recorded openly: they are design decisions with a stated reason in `analytics/standards_check.csv` "
             "(column `how`), not failures that were tuned away.\n"]
    return "\n".join(lines)


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    (DOCS / "CAPSTONE_RESULTS.md").write_text(results_doc(), encoding="utf-8", newline="\n")
    (DOCS / "STANDARDS_COMPLIANCE.md").write_text(standards_doc(), encoding="utf-8", newline="\n")
    print("wrote docs/CAPSTONE_RESULTS.md and docs/STANDARDS_COMPLIANCE.md")


if __name__ == "__main__":
    main()
